# -*- coding: utf-8 -*-
"""分段曲线类型的『领域话术』单一事实来源 —— 防止把温度措辞用到压力/真空。

**同一套分段模型**（波浪式 / 多段线性式 / 前期线性+后期平台 / 单一线性 / 全程平台停滞 / 短步）
同时用于两个物理量，**算法完全一致**；区别只在『平台』的中文话术：

| 领域 | 平台 | 带宽 | 示例类型名 |
|---|---|---|---|
| 温度域（需求3 / 温度—功率） | **恒温** | 恒温带 | 前期线性+后期恒温 |
| 压力·真空域（需求4 / 真空度—蝶阀） | **恒压** | 恒压带 | 前期线性+后期恒压 |

> 教训：压力侧曾直接沿用温度的类型名，PPT 里出现「真空拟合：−16.1 Pa/min（前期线性+后期恒温）」，
> 与事实不符（真空不存在"恒温"）。凡输出给用户看的类型名/带宽名，一律经本模块取词。

用法::

    from seg_terms import terms
    VAC = terms("P")
    T_LINHOLD = VAC["lin_hold"]     # "前期线性+后期恒压"
    T_FLAT    = VAC["flat"]         # "全程恒压/停滞"
    T_BAND    = VAC["band"]         # "恒压带"

域代号：``"T"`` = 温度；``"P"`` = 压力/真空。
"""

# 平台（后期进入近水平段的）中文话术：温度域=恒温，压力/真空域=恒压
_HOLD = {"T": "恒温", "P": "恒压"}


def terms(domain):
    """按领域返回分段类型话术字典。domain 取 ``"T"``(温度) 或 ``"P"``(压力/真空)。"""
    if domain not in _HOLD:
        raise ValueError("domain 必须是 'T' 或 'P'，收到 %r" % (domain,))
    hold = _HOLD[domain]
    return {
        "domain": domain,
        "hold": hold,                          # 平台：恒温 / 恒压
        "band": "%s带" % hold,                  # 平台带宽：恒温带 / 恒压带
        "wave": "波浪式",
        "multi": "多段线性式",
        "lin_hold": "前期线性+后期%s" % hold,     # 前期线性+后期恒温 / 恒压
        "lin": "单一线性",
        "flat": "全程%s/停滞" % hold,            # 全程恒温/停滞 / 全程恒压/停滞
        "platform": "%s/平台" % hold,            # 分步明细的平台行方向：恒温/平台 / 恒压/平台
        "short": "短步(数据不足)",
    }


if __name__ == "__main__":
    for d in ("T", "P"):
        t = terms(d)
        print(d, "->", t["lin_hold"], "|", t["flat"], "|", t["band"], "|", t["platform"])
